function renderWorkSection() {
  const filtered = activeFilter === "All" 
    ? works 
    : works.filter(w => w.cat === activeFilter);

  // Update counter
  if (workIndexCount) {
    workIndexCount.textContent = `${filtered.length} Entr${filtered.length === 1 ? 'y' : 'ies'}`;
  }

  // Ensure selectedWorkId exists in current filtered set
  const exists = filtered.some(w => w.id === selectedWorkId);
  if (!exists && filtered.length > 0) {
    selectedWorkId = filtered[0].id;
  }

  // Render Left Vertical Index
  if (workIndexList) {
    workIndexList.innerHTML = filtered.map(w => {
      const isSelected = w.id === selectedWorkId;
      return `
        <div class="work-index-item ${isSelected ? 'work-index-item--selected' : ''}" 
             data-id="${w.id}" 
             tabindex="0" 
             role="option" 
             aria-selected="${isSelected}">
          <div class="wii-left">
            <span class="wii-marker" title="${w.cat}">${w.marker}</span>
            <span class="wii-num">${w.id}</span>
          </div>
          <div class="wii-body">
            <div class="wii-meta">
              <span class="wii-org">${w.org.split("·")[0].trim()}</span>
              <span class="wii-cat-pill">${w.cat}</span>
            </div>
            <h3 class="wii-title">${w.title}</h3>
            <p class="wii-sub">${w.summary}</p>
          </div>
          <div class="wii-right">
            <span class="wii-indicator" aria-hidden="true">${isSelected ? '✕' : '+'}</span>
            <span class="wii-date">${w.date.split("—")[0].trim()}</span>
          </div>
        </div>
      `;
    }).join("");

    // Event listeners on index items
    workIndexList.querySelectorAll(".work-index-item").forEach(item => {
      item.addEventListener("click", () => {
        const id = item.dataset.id;
        if (selectedWorkId === id) {
          // If already selected, open the deep modal
          const w = works.find(item => item.id === id);
          if (w) openModal(w);
        } else {
          selectWorkItem(id);
        }
      });

      item.addEventListener("keydown", (e) => {
        if (e.key === "Enter" || e.key === " ") {
          e.preventDefault();
          const id = item.dataset.id;
          if (selectedWorkId === id) {
            const w = works.find(item => item.id === id);
            if (w) openModal(w);
          } else {
            selectWorkItem(id);
          }
        }
      });
    });
  }

  // Render Right Hero Stage
  renderWorkStage();
}

function selectWorkItem(id, smoothScroll = true) {
  if (selectedWorkId === id) return;
  selectedWorkId = id;
  renderWorkSection();

  if (smoothScroll && workIndexList) {
    const selectedEl = workIndexList.querySelector(`[data-id="${id}"]`);
    if (selectedEl) {
      selectedEl.scrollIntoView({ behavior: "smooth", block: "nearest" });
    }
  }
}

// Wheel navigation inside the Work experience list: transitions items in focus
let lastWorkIndexWheelTime = 0;
function initWorkIndexScroll() {
  if (!workIndexList) return;

  workIndexList.addEventListener("wheel", (e) => {
    // If modal is open, let modal handle it
    if (workModalBackdrop && workModalBackdrop.classList.contains("is-open")) return;

    const delta = e.deltaY;
    if (Math.abs(delta) < 22) return;

    const filtered = activeFilter === "All" ? works : works.filter(w => w.cat === activeFilter);
    if (!filtered || filtered.length <= 1) return;

    const currentIndex = filtered.findIndex(w => w.id === selectedWorkId);
    if (currentIndex === -1) return;

    // Check boundary
    const isAtTop = currentIndex === 0 && delta < 0;
    const isAtBottom = currentIndex === filtered.length - 1 && delta > 0;

    // Only intercept when advancing within the list
    if (!isAtTop && !isAtBottom) {
      const now = performance.now();
      if (now - lastWorkIndexWheelTime < 240) {
        e.preventDefault();
        return;
      }
      lastWorkIndexWheelTime = now;
      e.preventDefault();

      const nextIndex = delta > 0 ? currentIndex + 1 : currentIndex - 1;
      selectWorkItem(filtered[nextIndex].id, true);
    }
  }, { passive: false });
}

